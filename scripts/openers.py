"""Write the compatibility pages from hardware/openers/*.yaml.

One YAML file per opener model is the record; the pages on the site are
generated from them, so adding a model is one file and no page editing.

    uv run python scripts/openers.py            # write docs/compatibility.md and docs/openers/
    uv run python scripts/openers.py --check    # exit 1 if a page is stale or a file is invalid
"""

from __future__ import annotations

import argparse
import pathlib
import sys
from typing import Any

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "hardware/openers"
INDEX = ROOT / "docs/compatibility.md"
PAGES = ROOT / "docs/openers"
STATUS = {
    "tested": "Works: built and used on a real door",
    "untested": "Expected to work, not tried yet",
    "does-not-work": "Does not work",
}
REQUIRED = ("brand", "model", "region", "status", "manual", "push_button", "leave_alone", "notes")
HEADER = (
    "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->\n"
    "<!-- Generated by scripts/openers.py from hardware/openers/. Do not edit. -->\n"
)


def problems(name: str, model: dict[str, Any]) -> list[str]:
    """What is missing or wrong in one model file; empty when it is fine."""
    found = [f"{name}: missing {key}" for key in REQUIRED if key not in model]
    if model.get("status") not in STATUS:
        found.append(f"{name}: status must be one of {', '.join(STATUS)}")
    button = model.get("push_button")
    if not isinstance(button, dict) or not button.get("terminals") or not button.get("source"):
        found.append(f"{name}: push_button needs terminals and a source")
    return found


def load() -> dict[str, dict[str, Any]]:
    """Every model file, by its file name without the extension."""
    return {
        path.stem: yaml.safe_load(path.read_text())
        for path in sorted(SOURCE.glob("*.yaml"))
        if not path.name.startswith("_")
    }


def model_page(slug: str, m: dict[str, Any]) -> str:
    """One opener's page."""
    manual, button = m["manual"], m["push_button"]
    manual_line = (
        f"{manual.get('title') or 'not recorded'}, document {manual.get('document') or '?'}"
        f" ([download]({manual.get('url')}))"
    )
    terminals = " and ".join(str(t) for t in button["terminals"])
    volts = button.get("volts_open_circuit")
    leave = "\n".join(f"- {item}" for item in m["leave_alone"]) or "- Nothing listed."
    also = ", ".join(m.get("also_sold_as") or []) or "none known"
    by = m.get("reported_by") or "nobody yet"
    build = f"[{m['build']}]({m['build']})" if m.get("build") else "none yet"
    return f"""{HEADER}
# {m["brand"]} {m["model"]}

**Status:** {STATUS[str(m["status"])]}.

| | |
|---|---|
| Brand and model | {m["brand"]} {m["model"]} |
| Also sold as | {also} |
| Region | {m["region"]} |
| Manual | {manual_line} |
| Push-button terminals | **{terminals}** ({button["source"]}) |
| Voltage across them, open | {f"{volts} V (measured)" if volts is not None else "not measured yet"} |
| Reported by | {by} |
| A build | {build} |

## Leave alone

{leave}

## Notes

{str(m["notes"]).strip()}

Source: [`hardware/openers/{slug}.yaml`](https://github.com/roykollensvendsen/garage-door/blob/main/hardware/openers/{slug}.yaml).
To correct it, edit that file; see [Add your opener](../compatibility.md#add-your-opener).
"""


def index_page(models: dict[str, dict[str, Any]]) -> str:
    """The list of every opener, and how to add one."""
    rows = "\n".join(
        f"| [{m['brand']} {m['model']}](openers/{slug}.md) | {m['region']} | "
        f"{' and '.join(str(t) for t in m['push_button']['terminals'])} | {STATUS[str(m['status'])]} |"
        for slug, m in sorted(models.items(), key=lambda kv: (str(kv[1]["brand"]), str(kv[1]["model"])))
    )
    return f"""{HEADER}
# Does it work with your opener?

The controller needs one thing from an opener: a **wall push-button input**
that starts, stops and reverses the door when two terminals are briefly joined.
Most garage door openers have one. These are the models we know about.

| Opener | Region | Push-button terminals | Status |
|---|---|---|---|
{rows}

"Expected to work" means the manual shows the same push-button input, but
nobody has built the controller for that model yet. Be the first, and tell us.

## Add your opener

Adding your opener is the easiest way to contribute, and the most useful.

1. Find your opener's manual and the page that shows the wall push-button
   terminals.
2. Copy [`hardware/openers/_template.yaml`](https://github.com/roykollensvendsen/garage-door/blob/main/hardware/openers/_template.yaml)
   to `hardware/openers/<model>.yaml` and fill it in. Cite a manual page for
   every terminal, and never copy the manual's text.
3. Run `just docs` to see your page, and open a pull request.

Not sure? [Open an "add my opener" issue](https://github.com/roykollensvendsen/garage-door/issues/new?template=add-opener-model.yml)
with the model and a photo of the terminal block, and we will help. A coding
agent can do it with the project skill `add-opener-model`.
"""


def outputs() -> dict[pathlib.Path, str]:
    """Every page this writes, and its text."""
    models = load()
    errors = [p for slug, m in models.items() for p in problems(slug, m)]
    if errors:
        raise SystemExit("\n".join(errors))
    pages = {PAGES / f"{slug}.md": model_page(slug, m) for slug, m in models.items()}
    return {INDEX: index_page(models), **pages}


def main() -> int:
    """Write the pages, or with --check report whether the committed ones are current."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a page is stale")
    args = parser.parse_args()
    files = outputs()
    stale = [p for p, text in files.items() if not p.exists() or p.read_text() != text]
    orphans = [p for p in PAGES.glob("*.md") if p not in files]
    if args.check:
        for path in stale + orphans:
            sys.stderr.write(
                f"{path.relative_to(ROOT)} is out of date: run uv run python scripts/openers.py\n"
            )
        return 1 if stale or orphans else 0
    PAGES.mkdir(parents=True, exist_ok=True)
    for path in orphans:
        path.unlink()
    for path, text in files.items():
        path.write_text(text)
    sys.stdout.write(f"wrote {len(files)} pages for {len(files) - 1} openers\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
